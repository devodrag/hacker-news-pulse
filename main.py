"""
Hacker News Daily Pulse & Tech Intelligence Crawler
Zero external dependencies (uses standard library urllib, json, datetime).
"""

import os
import json
import datetime
import urllib.request
import urllib.error

USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) HNPulseBot/1.0"

def fetch_json(url):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            return json.loads(resp.read().decode("utf-8"))
    except Exception as e:
        print(f"[-] Warning: Failed to fetch {url}: {e}")
        return None

def fetch_story_details(story_id):
    url = f"https://hacker-news.firebaseio.com/v0/item/{story_id}.json"
    data = fetch_json(url)
    if data and "title" in data:
        return {
            "id": data["id"],
            "title": data["title"],
            "url": data.get("url", f"https://news.ycombinator.com/item?id={story_id}"),
            "hn_url": f"https://news.ycombinator.com/item?id={story_id}",
            "score": data.get("score", 0),
            "comments": data.get("descendants", 0),
            "by": data.get("by", "anonymous")
        }
    return None

def get_hn_pulse():
    categories = {
        "Top Intelligence": "https://hacker-news.firebaseio.com/v0/topstories.json",
        "Show HN (New Tools)": "https://hacker-news.firebaseio.com/v0/showstories.json",
        "Ask HN (Discussions)": "https://hacker-news.firebaseio.com/v0/askstories.json"
    }
    
    results = {}
    for cat_name, endpoint in categories.items():
        ids = fetch_json(endpoint)
        cat_stories = []
        if ids:
            limit = 5 if "Top" in cat_name else 3
            for item_id in ids[:limit * 2]:
                story = fetch_story_details(item_id)
                if story:
                    cat_stories.append(story)
                if len(cat_stories) >= limit:
                    break
        results[cat_name] = cat_stories
    return results

def generate_markdown(date_str, sections):
    lines = []
    lines.append(f"# 📰 Hacker News Daily Pulse // {date_str}\n")
    lines.append(f"> Automated tech journalism and developer intelligence. Generated by `devodrag/hacker-news-pulse`.\n")
    
    for section_name, stories in sections.items():
        lines.append(f"## ⚡ {section_name}\n")
        if not stories:
            lines.append("_No entries captured today._\n")
            continue
        for s in stories:
            lines.append(f"- **[{s['title']}]({s['url']})**")
            lines.append(f"  `▲ {s['score']} pts` &nbsp;·&nbsp; [💬 {s['comments']} comments]({s['hn_url']}) &nbsp;·&nbsp; _by {s['by']}_\n")
            
    lines.append("\n---\n<sub>( • ) devodrag · Automated Hacker News telemetry</sub>\n")
    return "\n".join(lines)

def update_root_readme(date_str, sections):
    content = [
        '<div align="center">',
        '  <p><code><b>( • ) HACKER NEWS PULSE &nbsp;|&nbsp; AUTOMATED DAILY DIGEST</b></code></p>',
        f'  <h1><b>HN PULSE // {date_str}</b></h1>',
        '  <p>Curated developer intelligence, trending engineering debates, and community showcases.</p>',
        '</div>',
        '',
        '---',
        ''
    ]
    
    idx = 1
    for section_name, stories in sections.items():
        content.append(f"### <code>( 0{idx} ) // {section_name.upper()}</code>")
        content.append('')
        if not stories:
            content.append("_No entries indexed for this category._\n")
        else:
            for s in stories:
                content.append(f"- **[{s['title']}]({s['url']})**")
                content.append(f"  `▲ {s['score']} pts` &nbsp;·&nbsp; [💬 {s['comments']} comments]({s['hn_url']}) &nbsp;·&nbsp; <sub>by {s['by']}</sub>\n")
        content.append('---')
        content.append('')
        idx += 1
        
    content.append('### <code>( 04 ) // ARCHIVE ACCESS</code>')
    content.append('')
    content.append(f"Past daily digests are permanently archived under [`archive/`](./archive/).")
    content.append('')
    content.append('<div align="center">')
    content.append('  <sub>Maintained automatically by <a href="https://github.com/devodrag">devodrag</a> via GitHub Actions</sub>')
    content.append('</div>')
    
    return "\n".join(content)

def main():
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    print(f"[*] Running Hacker News Pulse for {today}...")
    
    os.makedirs("archive", exist_ok=True)
    
    sections = get_hn_pulse()
    
    # 1. Archive
    archive_path = os.path.join("archive", f"{today}.md")
    archive_md = generate_markdown(today, sections)
    with open(archive_path, "w", encoding="utf-8") as f:
        f.write(archive_md)
    print(f"[+] Saved archive: {archive_path}")
    
    # 2. README.md
    readme_md = update_root_readme(today, sections)
    with open("README.md", "w", encoding="utf-8") as f:
        f.write(readme_md)
    print(f"[+] Updated root README.md")

if __name__ == "__main__":
    main()
